#include <iostream>
using namespace std;

int main() {
    int a[10];

    // Заповнення масиву за заданими формулами
    for (int i = 0; i < 10; i++) {
        if (i % 2 == 0) {
            a[i] = i + 5;  // Для парних індексів
        }
        else {
            a[i] = i - 5;  // Для непарних індексів
        }
    }

    // Виведення початкового масиву
    cout << "Початковий масив: ";
    for (int i = 0; i < 10; i++) {
        cout << a[i] << " ";
    }

    // Сортування бульбашкою за зростанням
    for (int i = 0; i < 10; i++) {
        for (int j = 0; j < 10 - i; j++) {

            // Якщо поточний елемент більший за наступний,
            // міняємо їх місцями
            if (a[j] > a[j + 1]) {
                int temp = a[j];
                a[j] = a[j + 1];
                a[j + 1] = temp;
            }
        }
    }

    // Виведення відсортованого масиву
    cout << "\nВідсортований масив: ";
    for (int i = 0; i < 10; i++) {
        cout << a[i] << " ";
    }

    return 0;
}